from __future__ import annotations

from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

NAVY = colors.HexColor("#0f1b2d")


def _tbl(rows, widths=None):
    t = Table(rows, colWidths=widths, repeatRows=1)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                           ("FONTSIZE", (0, 0), (-1, -1), 8), ("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
                           ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f3f5f8")])]))
    return t


def _f(v, nd=2):
    return "—" if v is None else (f"{v:,.{nd}f}" if isinstance(v, float) else str(v))


def render_pdf(report, out: Path) -> None:
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=NAVY, fontSize=18, alignment=0)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=NAVY, fontSize=12, spaceBefore=10)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9, leading=12)
    tag = ParagraphStyle("tag", parent=body, textColor=colors.HexColor("#555555"), fontSize=8)
    d = report.data
    doc = SimpleDocTemplate(str(out), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title=report.title, author="TerraTrace AI")
    S = [Paragraph("TerraTrace AI — Geospatial Change Intelligence", tag), Paragraph(report.title, h1),
         Paragraph(f"Report {report.id} · generated {d['generated_at']} · Project: {d['project']['name']}", tag), Spacer(1, 6)]
    S.append(Paragraph("<b>Provenance legend</b> — [MODEL] model prediction · [CALC] calculated statistic · [HUMAN] human-verified · "
                       "[AI] AI-generated narrative", tag))
    if report.kind == "analysis":
        a = d["analysis"]; cs = d["calculated_statistics"]
        S.append(Paragraph("1. Analysis overview [CALC]", h2))
        S.append(_tbl([["Item", "Value"], ["Analysis", a["analysis_id"]], ["Before → After", f"{a['before_date']} → {a['after_date']}"],
                       ["Georeferenced", "yes" if d["georeferenced"] else "no (image-relative coordinates only)"],
                       ["Candidate events [MODEL]", a["n_events"]], ["Clusters", a["n_clusters"]],
                       ["Changed share of image", _f(cs["changed_pct"]) + " %"], ["Changed pixels", _f(cs["changed_pixels"], 0)],
                       ["Changed area (geodesic)", (_f(cs["changed_area_m2"], 1) + " m²") if cs["changed_area_m2"] is not None else "n/a (not georeferenced)"],
                       ["Mean model confidence", _f(a["mean_confidence"], 3)], ["Alignment", str(a["alignment_status"])],
                       ["Domain compatibility", str(a["domain_compatibility"])]], [60 * mm, 110 * mm]))
        if report.narrative:
            S += [Paragraph(f"Narrative [AI — generated by {report.narrative_provider}; numbers are from the tables in this report]", h2),
                  Paragraph(report.narrative.replace("\n", "<br/>"), body)]
        S.append(Paragraph("2. Human verification [HUMAN]", h2))
        hv = d["human_verification"]["counts"]
        S.append(_tbl([["Status", "Events"]] + [[k.replace("_", " "), v] for k, v in hv.items()], [60 * mm, 40 * mm]))
        S.append(Paragraph("3. Confidence distribution [CALC]", h2))
        S.append(_tbl([["Mean confidence range", "Events"]] + [[r["range"], r["count"]] for r in cs["confidence_distribution"]], [60 * mm, 40 * mm]))
        S.append(Paragraph("4. Analytical priority distribution [CALC]", h2))
        S.append(_tbl([["Priority score range", "Events"]] + [[r["range"], r["count"]] for r in cs["priority_distribution"]], [60 * mm, 40 * mm]))
        S.append(Paragraph("5. Clusters [CALC]", h2))
        S.append(_tbl([["Cluster", "Events", "Area px", "Area m²", "Mean conf.", "Priority"]] +
                      [[c["cluster_id"], c["event_count"], _f(c["total_area_px"], 0), _f(c["total_area_m2"], 1), _f(c["mean_confidence"], 3), _f(c["priority_score"], 1)]
                       for c in d["clusters"]] or [["none", "", "", "", "", ""]]))
        S.append(Paragraph("6. Top candidate events by analytical priority [MODEL + CALC]", h2))
        S.append(_tbl([["Event", "Conf.", "Area px", "Area m²", "Priority", "Cluster", "Review", "Temporal"]] +
                      [[e["event_id"], _f(e["confidence"], 3), _f(e["area_px"], 0), _f(e["area_m2"], 1), _f(e["priority_score"], 1),
                        e["cluster"] or "—", e["review_status"], e["temporal_status"]] for e in d["top_events"]] or [["none"] + [""] * 7]))
        S.append(Paragraph("7. Model & methodology", h2))
        mdl = d["model"]
        S.append(Paragraph(f"Architecture: {mdl['architecture'] or 'n/a'} · dataset: {mdl['dataset']} · "
                           f"validated on LEVIR-CD test split: {'yes' if mdl['validated_on_test'] else 'no'}", body))
        if mdl["test_metrics"]:
            t = mdl["test_metrics"]
            S.append(Paragraph(f"LEVIR-CD test: F1 {t['f1']:.3f}, IoU {t['iou']:.3f}, precision {t['precision']:.3f}, recall {t['recall']:.3f} "
                               "(in-domain only; not a statement about this imagery).", body))
        for line in d["methodology"]:
            S.append(Paragraph("• " + line, body))
    else:
        c = d["comparison"]; A, B = c["analysis_a"], c["analysis_b"]
        S.append(Paragraph("1. Comparison [CALC]", h2))
        S.append(_tbl([["Metric", f"A {A['analysis_id']}", f"B {B['analysis_id']}", "Δ (B−A)"],
                       ["Period", f"{A['before_date']}→{A['after_date']}", f"{B['before_date']}→{B['after_date']}", ""],
                       ["Candidate events", A["n_events"], B["n_events"], c["delta"]["n_events"]],
                       ["Changed %", _f(A["changed_pct"]), _f(B["changed_pct"]), _f(c["delta"]["changed_pct"])],
                       ["Changed area m²", _f(A["changed_area_m2"], 1), _f(B["changed_area_m2"], 1), _f(c["delta"]["changed_area_m2"], 1)]]))
        S.append(Paragraph(f"New in B: {', '.join(c['new_in_b']) or 'none'}", body))
        S.append(Paragraph(f"Persisting: {', '.join(c['persisting']) or 'none'}", body))
        S.append(Paragraph(f"Not detected in B: {', '.join(c['not_detected_in_b']) or 'none'}", body))
        if report.narrative:
            S += [Paragraph(f"Narrative [AI — {report.narrative_provider}]", h2), Paragraph(report.narrative.replace("\n", "<br/>"), body)]
    S.append(Paragraph("Limitations", h2))
    for l in d["limitations"]:
        S.append(Paragraph("• " + l, body))
    doc.build(S)
